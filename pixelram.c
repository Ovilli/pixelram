bool screen_open(int width, int height, pixel_mode mode, const char *title) {
    if (pr.initialized || width <= 0 || height <= 0) {
        return false;
    }
    int bpp = bytes_per_pixel(mode);
    if (bpp == 0)
        return false;
    pr.width = width;
    pr.height = height;
    pr.pitch = width * bpp;
    pr.mode = mode;
    pr.framebuffer_size = (size_t)pr.pitch * (size_t)height;
    pr.framebuffer = (unsigned char *)calloc(1, pr.framebuffer_size);
    pr.rgba = (Color *)calloc((size_t)width * (size_t)height, sizeof(Color));
    if (!pr.framebuffer || !pr.rgba) {
        free(pr.framebuffer);
        free(pr.rgba);
        memset(&pr, 0, sizeof(pr));
        return false;
    }
    make_default_palette();
    SetTraceLogLevel(LOG_WARNING);
    InitWindow(width, height, title ? title : "PixelRAM");

    /*
     * Escape belongs to the program. It must not make raylib close
     * the window automatically; DOOM in particular needs it for menus.
     */
    SetExitKey(KEY_NULL);

#ifdef PLATFORM_WEB
    pixelram_install_web_handlers();
#endif

    Image image = {
        .data = pr.rgba,
        .width = width,
        .height = height,
        .mipmaps = 1,
        .format = PIXELFORMAT_UNCOMPRESSED_R8G8B8A8
    };
    pr.texture = LoadTextureFromImage(image);
    if (pr.texture.id == 0) {
        CloseWindow();
        free(pr.framebuffer);
        free(pr.rgba);
        memset(&pr, 0, sizeof(pr));
        return false;
    }
    SetTextureFilter(pr.texture, TEXTURE_FILTER_POINT);
    pr.target_fps = 60;
    pr.next_present_time = GetTime() + 1.0 / 60.0;

#ifndef PLATFORM_WEB
    SetTargetFPS(pr.target_fps);
#endif

    pr.initialized = true;
    pr.mouse_relative = false;
    pr.explicit_presented = false;

#ifdef PLATFORM_WEB
    web_mouse_x = 0;
    web_mouse_y = 0;
    web_mouse_dx = 0;
    web_mouse_dy = 0;
    web_mouse_position_valid = false;
    web_mouse_buttons_down = 0;
    web_mouse_pressed_pending = 0;
    web_mouse_released_pending = 0;
    pr.mouse_pressed_frame = 0;
    pr.mouse_released_frame = 0;
#endif

    set_pixel_aspect(1.0f);
    return true;
}

bool screen_set_mode(int width, int height, pixel_mode mode) {
    if (!pr.initialized || width <= 0 || height <= 0) {
        return false;
    }
    int bpp = bytes_per_pixel(mode);
    if (bpp == 0)
        return false;
    if (width == pr.width && height == pr.height && mode == pr.mode) {
        return true;
    }
    int new_pitch = width * bpp;
    size_t new_framebuffer_size = (size_t)new_pitch * (size_t)height;
    unsigned char *new_framebuffer = (unsigned char *)calloc(1, new_framebuffer_size);
    Color *new_rgba = (Color *)calloc((size_t)width * (size_t)height, sizeof(Color));
    if (!new_framebuffer || !new_rgba) {
        free(new_framebuffer);
        free(new_rgba);
        return false;
    }
    Image image = {
        .data = new_rgba,
        .width = width,
        .height = height,
        .mipmaps = 1,
        .format = PIXELFORMAT_UNCOMPRESSED_R8G8B8A8
    };
    Texture2D new_texture = LoadTextureFromImage(image);
    if (new_texture.id == 0) {
        free(new_framebuffer);
        free(new_rgba);
        return false;
    }
    SetTextureFilter(new_texture, TEXTURE_FILTER_POINT);
    UnloadTexture(pr.texture);
    free(pr.framebuffer);
    free(pr.rgba);
    pr.width = width;
    pr.height = height;
    pr.pitch = new_pitch;
    pr.mode = mode;
    pr.framebuffer = new_framebuffer;
    pr.framebuffer_size = new_framebuffer_size;
    pr.rgba = new_rgba;
    pr.texture = new_texture;

    /* Update the window/canvas backing size after a mode change. */
    SetWindowSize(width, height);
    return true;
}

