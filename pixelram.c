static int bytes_per_pixel(pixel_mode mode) {
    switch (mode) {
        case pixel_indexed8: return 1;
        case pixel_rgb565:   return 2;
        case pixel_rgb24:    return 3;
        case pixel_rgba32:   return 4;
        default:           return 0;
    }
}

static int raylib_key(pixel_key key) {
    for (size_t i = 0; i < sizeof(key_map) / sizeof(key_map[0]); i++) {
        if (key_map[i].code == key)
            return key_map[i].raylib;
    }

    switch (key) {
        case pixel_key_shift:
            return KEY_LEFT_SHIFT;
        case pixel_key_ctrl:
            return KEY_LEFT_CONTROL;
        case pixel_key_alt:
            return KEY_LEFT_ALT;
        default:
            return KEY_NULL;
    }
}

static bool modifier_down(int left, int right) {
    return IsKeyDown(left) || IsKeyDown(right);
}

static bool modifier_pressed(int left, int right) {
    return IsKeyPressed(left) || IsKeyPressed(right);
}

static bool modifier_released(int left, int right) {
    /*
     * Only report "modifier released" when neither side is still held.
     */
    return (IsKeyReleased(left) || IsKeyReleased(right)) && !modifier_down(left, right);
}

static void queue_key_event(pixel_key key, bool pressed) {
    if ((int)key >= 0 && (int)key < PIXELRAM_KEY_STATE_SIZE) {
        if (pressed)
            pr.key_pressed_frame[(int)key] = true;
        else
            pr.key_released_frame[(int)key] = true;
    }

    unsigned int next = (pr.key_write + 1) % PIXELRAM_KEY_QUEUE_SIZE;

    /*
     * If full, drop the oldest event rather than blocking rendering.
     */
    if (next == pr.key_read) {
        pr.key_read = (pr.key_read + 1) % PIXELRAM_KEY_QUEUE_SIZE;
    }
    pr.key_queue[pr.key_write] = (pixel_key_event){
        .key = key,
        .pressed = pressed
    };
    pr.key_write = next;
}

static void pump_key_events(void) {
    memset(pr.key_pressed_frame, 0, sizeof(pr.key_pressed_frame));
    memset(pr.key_released_frame, 0, sizeof(pr.key_released_frame));

#ifdef PLATFORM_WEB
    /*
     * raylib/GLFW tracks browser keys globally, so DOM stopPropagation() on
     * the ARGS input is not sufficient.  While an HTML text field owns the
     * keyboard, drop PixelRAM's queued game events as well.
     */
    if (pixelram_web_text_input_active()) {
        pr.key_read = pr.key_write;
        return;
    }
#endif

    for (size_t i = 0; i < sizeof(key_map) / sizeof(key_map[0]); i++) {
        int key = key_map[i].raylib;
        if (IsKeyPressed(key)) {
            queue_key_event(key_map[i].code, true);
        }

        if (IsKeyReleased(key)) {
            queue_key_event(key_map[i].code, false);
        }
    }

    if (modifier_pressed(KEY_LEFT_SHIFT, KEY_RIGHT_SHIFT)) {
        queue_key_event(pixel_key_shift, true);
    }

    if (modifier_released(KEY_LEFT_SHIFT, KEY_RIGHT_SHIFT)) {
        queue_key_event(pixel_key_shift, false);
    }

    if (modifier_pressed(KEY_LEFT_CONTROL, KEY_RIGHT_CONTROL)) {
        queue_key_event(pixel_key_ctrl, true);
    }

    if (modifier_released(KEY_LEFT_CONTROL, KEY_RIGHT_CONTROL)) {
        queue_key_event(pixel_key_ctrl, false);
    }

    if (modifier_pressed(KEY_LEFT_ALT, KEY_RIGHT_ALT)) {
        queue_key_event(pixel_key_alt, true);
    }

    if (modifier_released(KEY_LEFT_ALT, KEY_RIGHT_ALT)) {
        queue_key_event(pixel_key_alt, false);
    }
}

