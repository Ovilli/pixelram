void set_pixel_rgb(int x, int y, uint8_t r, uint8_t g, uint8_t b) {
    if (!pr.initialized || x < 0 || y < 0 || x >= pr.width || y >= pr.height) {
        return;
    }
    size_t pixel = (size_t)y * (size_t)pr.width + (size_t)x;
    switch (pr.mode) {
        case pixel_indexed8:
            break;
        case pixel_rgb565:
            ((uint16_t *)pr.framebuffer)[pixel] = rgb565_pack(r, g, b);
            break;
        case pixel_rgb24: {
            uint8_t *dst = pr.framebuffer + pixel * 3;
            dst[0] = r;
            dst[1] = g;
            dst[2] = b;
            break;
        }
        case pixel_rgba32: {
            uint8_t *dst = pr.framebuffer + pixel * 4;
            dst[0] = r;
            dst[1] = g;
            dst[2] = b;
            dst[3] = 255;
            break;
        }
    }
    framebuffer_changed();
}

bool get_pixel_rgb(int x, int y, uint8_t *r, uint8_t *g, uint8_t *b) {
    uint8_t rr = 0;
    uint8_t gg = 0;
    uint8_t bb = 0;
    if (!pr.initialized || x < 0 || y < 0 || x >= pr.width || y >= pr.height) {
        if (r) *r = 0;
        if (g) *g = 0;
        if (b) *b = 0;
        return false;
    }
    size_t pixel = (size_t)y * (size_t)pr.width + (size_t)x;
    switch (pr.mode) {
        case pixel_indexed8: {
            uint8_t index = ((const uint8_t *)pr.framebuffer)[pixel];
            rr = pr.palette[index].r;
            gg = pr.palette[index].g;
            bb = pr.palette[index].b;
            break;
        }
        case pixel_rgb565: {
            uint16_t value = ((const uint16_t *)pr.framebuffer)[pixel];
            unsigned int r5 = (value >> 11) & 0x1f;
            unsigned int g6 = (value >> 5) & 0x3f;
            unsigned int b5 = value & 0x1f;
            rr = (uint8_t)((r5 * 255u + 15u) / 31u);
            gg = (uint8_t)((g6 * 255u + 31u) / 63u);
            bb = (uint8_t)((b5 * 255u + 15u) / 31u);
            break;
        }
        case pixel_rgb24: {
            const uint8_t *src = pr.framebuffer + pixel * 3;
            rr = src[0];
            gg = src[1];
            bb = src[2];
            break;
        }
        case pixel_rgba32: {
            const uint8_t *src = pr.framebuffer + pixel * 4;
            rr = src[0];
            gg = src[1];
            bb = src[2];
            break;
        }
    }

    if (r) *r = rr;
    if (g) *g = gg;
    if (b) *b = bb;
    return true;
}