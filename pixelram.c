bool poll_key_event(pixel_key_event *event) {
    if (!event || pr.key_read == pr.key_write) {
        return false;
    }

    *event = pr.key_queue[pr.key_read];
    pr.key_read = (pr.key_read + 1) % PIXELRAM_KEY_QUEUE_SIZE;
    return true;
}

